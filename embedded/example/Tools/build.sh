#!/usr/bin/env bash

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)" 
PRESET="${1:-Debug}"

TOOLCHAIN_FILE="$ROOT_DIR/cmake/gcc-arm-none-eabi.cmake"
CUBEMX_CMAKE="$ROOT_DIR/cmake/stm32cubemx/CMakeLists.txt"

if [ ! -f "$TOOLCHAIN_FILE" ] || [ ! -f "$CUBEMX_CMAKE" ]; then
    cat >&2 <<EOF
Firmware files generated by CubeMX were not found.

Generate a CMake project with CubeMX directly into:
  $ROOT_DIR

To run only tests, run:
  Tools/test.sh
EOF

    exit 1
fi

cd "$ROOT_DIR" 

cmake --preset "$PRESET"
cmake --build --preset "$PRESET"